#!/usr/bin/env python3
"""Build 700 compact, bidirectional legal recall prompts from authored subject/topic seeds.
No external scraping, automated copying or API calls. Existing source concepts are in concepts.txt.
"""
from __future__ import annotations
import csv, json, re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sections = []
course = None
for raw in (ROOT / 'concepts.txt').read_text(encoding='utf-8').splitlines():
    line = raw.strip()
    if not line or line.startswith('# '):
        continue
    if line.startswith('## '):
        course = line[3:].strip()
        sections.append((course, []))
        continue
    if course is None: raise ValueError('Missing heading before data')
    parts = [x.strip() for x in line.split(' | ')]
    if len(parts) != 3: raise ValueError(f'Malformed concept seed: {line[:80]}')
    sections[-1][1].append(parts)

assert len(sections) == 70
all_cards = []
for course_idx, (subject, concepts) in enumerate(sections, start=1):
    assert len(concepts) == 10, (subject, len(concepts))
    for i, (term, definition, citation) in enumerate(concepts):
        # Exactly half require free recall of the rule from its name;
        # the other half require retrieval of the doctrine from an application.
        if i % 2 == 0:
            prompts = [
                f'In {subject}, what does “{term}” mean?',
                f'What is the legal significance of “{term}”?',
                f'What should you remember about “{term}”?',
                f'Describe the doctrine or rule of “{term}.”',
                f'What does “{term}” address in this subject?',
            ]
            front = prompts[i // 2]
            back = definition
            kind = 'Rule / concept recall'
        else:
            prompts = [
                'Identify the doctrine or concept: ',
                'Which legal term best fits this description? ',
                'Name the governing principle: ',
                'What is the rule, doctrine, or concept? ',
                'Identify the legal concept illustrated: ',
            ]
            front = prompts[i // 2] + definition
            back = term + '.'
            kind = 'Fact pattern / doctrine identification'
        card = {
            'id':f'ec-{course_idx:02d}-{i+1:02d}',
            'course':subject,
            'topic':term,
            'front':front,
            'back':back,
            'authority':citation,
            'source':'builtin',
            'format':kind
        }
        all_cards.append(card)

assert len(all_cards) == 700
assert len(set(x['id'] for x in all_cards)) == 700
assert len(set((x['course'], x['front'].casefold()) for x in all_cards)) == 700
assert all(x['authority'] and len(x['front']) <= 250 and len(x['back']) <= 250 for x in all_cards)
assert not any(x['topic'].lower() in x['front'].lower().split('description: ')[-1] for x in all_cards if x['format'].startswith('Fact'))
assert Counter(x['course'] for x in all_cards) == Counter({n:10 for n,_ in sections})

json_text = json.dumps(all_cards, ensure_ascii=False, indent=2)
(ROOT/'expanded-flashcards.json').write_text(json_text+'\n', encoding='utf-8')
with (ROOT/'expanded-flashcards.csv').open('w', newline='', encoding='utf-8-sig') as h:
    w=csv.DictWriter(h, fieldnames=['id','course','topic','format','front','back','authority'])
    w.writeheader()
    w.writerows(({k:x[k] for k in w.fieldnames} for x in all_cards))
(ROOT/'expanded-flashcards.js').write_text(
    '// 700 additional original study flashcards: 10 per subject.\n'
    '// Generated by build_flashcards.py from the authored legal-concept seeds in concepts.txt.\n'
    '// 350 rule-recall cards and 350 doctrine-identification cards.\n'
    'const EXPANDED_FLASHCARDS = '+json.dumps(all_cards,ensure_ascii=False,separators=(',',':'))+';\n'
    'BUILTIN_CARDS.push(...EXPANDED_FLASHCARDS);\n', encoding='utf-8')

print('Built',len(all_cards),'additional flashcards across',len(sections),'subjects')
print('Rule recall:',sum(x['format'].startswith('Rule') for x in all_cards))
print('Identification:',sum(x['format'].startswith('Fact') for x in all_cards))
